#!/usr/bin/env python3
"""Generate the exact anchored SHF cases as checked Lean Boolean statements.

The index sets are generated independently for each k.  There is no SAT result
embedded here: each emitted semantic block is proved using existing Lean
lemmas, and each case still has to pass bv_decide? or bv_check.

Initial generation:
    python3 research/direct-matrix/generate_compact_cases.py --replay 2
After saving all four successful certificates under certificates/caseK.lrat:
    python3 research/direct-matrix/generate_compact_cases.py --replay 2 3 4 5

Run searches with an absolute .lean filename; the Lean certificate-writing
frontend requires it.  Replay modules use stable relative certificate paths.
The script never launches Lean or an external SAT solver.
"""

from __future__ import annotations

import argparse
import itertools
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from typing import Callable


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_PROJECT = ROOT / "gpt6_astra"
CONFIG = (
    '{ timeout := 120, maxSteps := 2000000, structures := false, '
    '«enums» := false, fixedInt := false, embeddedConstraintSubst := false }'
)
DEPENDENCIES = ("hshf", "hfixed", "hanchor", "hrows", "hcols")


@dataclass(frozen=True)
class Constraint:
    expression: str
    proof: str
    dependency: str
    category: str


def balanced(items: list[str], combine: Callable[[str, str], str]) -> str:
    if len(items) == 1:
        return items[0]
    midpoint = len(items) // 2
    return combine(balanced(items[:midpoint], combine),
                   balanced(items[midpoint:], combine))


def bool_and(left: str, right: str) -> str:
    return f"({left} && {right})"


def proof_and(left: str, right: str) -> str:
    return f"(bool_and_intro ⟨{left}, {right}⟩)"


def constraints(k: int) -> list[Constraint]:
    assert k in (2, 3, 4, 5)
    result: list[Constraint] = []
    for c in range(10):
        result.append(Constraint(
            f"(A 0 {c} == decide (({c} : Fin 10).val < {k}))",
            f"(by simpa only [beq_iff_eq] using hfixed {c})",
            "hfixed", "fixed"))
    for r in range(1, 10):
        result.append(Constraint(
            f"(A {r} 0 == false)",
            f"(by simpa only [beq_iff_eq] using hanchor {r} (by decide))",
            "hanchor", "anchor"))
    for i in range(1, 9):
        for c in range(10):
            result.append(Constraint(
                f"(rowLexClause A {i} {i+1} {c})",
                f"(rowLexClause_of_doubleLexRows A hrows {i} {i+1} {c} "
                "(by decide) (by decide))", "hrows", "row"))
    for group in (list(range(1, k)), list(range(k, 10))):
        for c, d in zip(group, group[1:]):
            for r in range(1, 10):
                result.append(Constraint(
                    f"(columnLexClause A {c} {d} {r})",
                    f"(columnLexClause_of_doubleLexAnchoredColumns A {k} hcols "
                    f"{c} {d} {r} (by decide) (by decide) (by decide) (by decide))",
                    "hcols", "column"))
    for a in range(10):
        for b, c, d in itertools.combinations([i for i in range(10) if i != a], 3):
            result.append(Constraint(
                f"(separationClause A {a} {b} {c} {d})",
                f"(separationClause_of_isSHF A hshf {a} {b} {c} {d} "
                "(by decide) (by decide) (by decide) (by decide) (by decide) (by decide))",
                "hshf", "separation"))
    counts = Counter(item.category for item in result)
    assert counts == dict(fixed=10, anchor=9, row=80, column=63, separation=840)
    assert len({item.expression for item in result}) == 1002
    return result


def argument_types(k: int) -> dict[str, str]:
    return {
        "hshf": "(hshf : IsSHF A)",
        "hfixed": f"(hfixed : FixedRow A {k})",
        "hanchor": "(hanchor : AnchorZero A)",
        "hrows": "(hrows : DoubleLexRows A)",
        "hcols": f"(hcols : DoubleLexAnchoredColumns A {k})",
    }


def generate(k: int, replay: bool) -> str:
    clauses = constraints(k)
    types = argument_types(k)
    all_args = (f"(A : BinaryMatrix 10) {types['hshf']}\n"
                f"    {types['hfixed']} {types['hanchor']}\n"
                f"    {types['hrows']} {types['hcols']}")
    lines = [
        "import LexBoolean", "import FiniteCaseSupport", "import CanonicalBoolAtoms", "",
        "set_option autoImplicit false", "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 0", "set_option Elab.async false", "",
        "namespace GPT6Astra", "",
        "private theorem bool_and_intro {a b : Bool} (h : a = true ∧ b = true) :",
        "    (a && b) = true := by simp_all", "",
        "/- Generated by research/direct-matrix/generate_compact_cases.py.",
        "   The 1,002 semantic constraints are independently proved in balanced blocks. -/", "",
    ]
    block_names: list[str] = []
    block_proofs: list[str] = []
    for i, start in enumerate(range(0, len(clauses), 32)):
        block = clauses[start:start + 32]
        name = f"compact{k}Block{i:02d}"
        block_names.append(name)
        deps = [d for d in DEPENDENCIES if any(c.dependency == d for c in block)]
        block_proofs.append(f"({name}_eq_true A {' '.join(deps)})")
        lines += [
            f"private def {name} (A : BinaryMatrix 10) : Bool :=",
            "  " + balanced([c.expression for c in block], bool_and), "",
            f"private theorem {name}_eq_true (A : BinaryMatrix 10)",
            "    " + " ".join(types[d] for d in deps) + " :",
            f"    {name} A = true := by", f"  unfold {name}",
            "  exact " + balanced([c.proof for c in block], proof_and), "",
        ]
    lines += [
        f"def compact{k}Constraints (A : BinaryMatrix 10) : Bool :=",
        "  " + balanced([f"{name} A" for name in block_names], bool_and), "",
        f"theorem compact{k}Constraints_of_canonical {all_args} :",
        f"    compact{k}Constraints A = true := by",
        f"  unfold compact{k}Constraints",
        "  exact " + balanced(block_proofs, proof_and), "",
        f"theorem anchored_case_{k} {all_args} : False := by",
        f"  have hc := compact{k}Constraints_of_canonical A hshf hfixed hanchor hrows hcols",
        "  clear hshf hfixed hanchor hrows hcols",
        f"  simp only [compact{k}Constraints, " + ", ".join(block_names) + ",",
        "    separationClause, separatesB, rowLexClause, prefixB, columnLexClause, columnPrefixB] at hc",
        "  canonical_matrix_atoms A at hc",
        (f'  bv_check (config := {CONFIG}) "certificates/case{k}.lrat"' if replay
         else f"  bv_decide? (config := {CONFIG})"), "",
        f"#print axioms anchored_case_{k}", "", "end GPT6Astra", "",
    ]
    return "\n".join(lines)


def wrapper(k: int) -> str:
    return (
        f"import FiniteCase{k}\n\nnamespace GPT6Astra\n\n"
        f"/-- Compatibility name for the canonical case-{k} theorem. -/\n"
        f"theorem anchored_case_{k}_compact (A : BinaryMatrix 10) (hshf : IsSHF A)\n"
        f"    (hfixed : FixedRow A {k}) (hanchor : AnchorZero A)\n"
        f"    (hrows : DoubleLexRows A) (hcols : DoubleLexAnchoredColumns A {k}) : False :=\n"
        f"  anchored_case_{k} A hshf hfixed hanchor hrows hcols\n\nend GPT6Astra\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", type=Path, default=DEFAULT_PROJECT)
    parser.add_argument("--cases", type=int, nargs="+", choices=(2, 3, 4, 5), default=[2, 3, 4, 5])
    parser.add_argument("--replay", type=int, nargs="*", choices=(2, 3, 4, 5), default=[])
    args = parser.parse_args()
    for k in args.cases:
        replay = k in args.replay
        if replay and not (args.project / f"certificates/case{k}.lrat").is_file():
            parser.error(f"missing certificate for replay of case {k}")
        (args.project / f"FiniteCase{k}.lean").write_text(generate(k, replay))
        (args.project / f"FiniteCase{k}Compact.lean").write_text(wrapper(k))
        mode = "stable certificate replay" if replay else "certificate search; not yet verified"
        print(f"case {k}: 1002 constraints, 32 blocks, {mode}")


if __name__ == "__main__":
    main()
